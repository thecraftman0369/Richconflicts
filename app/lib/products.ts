/* ─── Helpers ─── */

export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id)
}

export function isSoldOut(product: Product): boolean {
  return (product.stock ?? 0) === 0
}

export function isInStock(product: Product, size: string): boolean {
  return (product.inventory?.[size] ?? 0) > 0
}

export function isNew(product: Product): boolean {
  return (
    product.isNew === true ||
    product.category === 'new-arrivals' ||
    (product.categories?.includes('new-arrivals') ?? false)
  )
}

export function firstAvailableSize(product: Product): string | undefined {
  return product.sizes?.find((s) => isInStock(product, s))
}

export function derivedCategories(): string[] {
  const raw = new Set<string>()
  products.forEach((p) => {
    raw.add(p.category)
    p.categories?.forEach((c) => raw.add(c))
  })
  return Array.from(raw)
}
